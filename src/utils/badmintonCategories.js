export const isCategoryInGroup = (category, groupId) => {
  if (groupId === 'all') return true
  if (groupId === 'popular') return POPULAR_CATEGORIES.includes(category)
  if (groupId === 'under') {
    return category.startsWith('Under ') || category.startsWith('Sub-Junior') || category.startsWith('Junior')
  }
  if (groupId === 'jumbled') {
    return category.toLowerCase().includes('jumbled')
  }
  if (groupId === 'masters') {
    return /\b\d{2}\+\b/.test(category) || category.includes('Veterans') || category.includes('Masters')
  }
  if (groupId === 'corporate') {
    return /Beginner|Amateur|Intermediate|Advanced|Corporate/.test(category)
  }
  if (groupId === 'family') {
    return /Father|Mother|Parent|Husband|Sibling/.test(category)
  }
  if (groupId === 'para') {
    return category.startsWith('Para ')
  }
  return true
}

// Smart Search function that matches acronyms, "u9", "under 9", "75+", "jumbled", etc.
export const matchesCategorySearch = (category, query) => {
  if (!query || !query.trim()) return true

  const q = query.toLowerCase().trim()
  const cat = category.toLowerCase()

  // Direct exact phrase match (if phrase has word boundaries for numbers)
  // Support "u9", "u-9", "u 9", "u09" -> matches "under 9" or "9+"
  const uMatch = q.match(/^u-?\s*(\d+)$/)
  if (uMatch) {
    const age = parseInt(uMatch[1], 10)
    return new RegExp(`\\bunder\\s+${age}\\b`).test(cat) || new RegExp(`\\b${age}\\+\\b`).test(cat)
  }

  // Common badminton acronym shortcuts
  if (q === 'ms' && cat.includes('men singles')) return true
  if (q === 'ws' && cat.includes('women singles')) return true
  if (q === 'md' && (cat.includes('men doubles') || cat.includes('jumbled doubles'))) return true
  if (q === 'wd' && cat.includes('women doubles')) return true
  if (q === 'xd' && (cat.includes('mixed doubles') || cat.includes('jumbled mixed'))) return true
  if (q === 'bs' && cat.includes('boys singles')) return true
  if (q === 'bd' && cat.includes('boys doubles')) return true
  if (q === 'gs' && cat.includes('girls singles')) return true
  if (q === 'gd' && cat.includes('girls doubles')) return true

  // Multi-token match (e.g. "u9 doubles", "under 9", "jumbled 70", "boys u13")
  const tokens = q.split(/\s+/).filter(Boolean)
  return tokens.every((token) => {
    // If token is "u9", "u-9", "u13" etc.
    const tokenUMatch = token.match(/^u-?(\d+)$/)
    if (tokenUMatch) {
      const age = parseInt(tokenUMatch[1], 10)
      return new RegExp(`\\bunder\\s+${age}\\b`).test(cat) || new RegExp(`\\b${age}\\+\\b`).test(cat)
    }
    // If token is purely a number (like "9", "11", "70")
    if (/^\d+$/.test(token)) {
      return new RegExp(`\\b${token}\\b`).test(cat)
    }
    // If token ends with + (like "70+", "75+")
    if (/^\d+\+$/.test(token)) {
      return new RegExp(`\\b${token.replace('+', '\\+')}`).test(cat)
    }
    return cat.includes(token)
  })
}

/**
 * Checks if a given category name is a doubles category (Men Doubles, Women Doubles, Mixed Doubles, Jumbled Doubles, etc.)
 */
export const isDoublesCategory = (categoryName) => {
  if (!categoryName || typeof categoryName !== 'string') return false
  const lower = categoryName.toLowerCase()
  return (
    lower.includes('doubles') ||
    lower.includes('mixed') ||
    lower.includes('pair') ||
    lower.includes('duo') ||
    /\b(md|wd|xd|bd|gd)\b/i.test(categoryName)
  )
}
